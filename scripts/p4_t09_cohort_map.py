#!/usr/bin/env python3
"""T09 — map of cohorts × questions: a two-dimensional picture of where cohorts sit and which answers pull them.

Principal components of the standardised cohorts × headline-measures matrix (same matrix as T08), by SVD.
Signs fixed so each component's largest loading is positive. Cohort coordinates and measure loadings
(a biplot). ECOLOGICAL: cohorts overlap. Writes outputs/T09/.
Usage: python3 -I scripts/p4_t09_cohort_map.py
"""
import sys
from pathlib import Path

sys.dont_write_bytecode = True
sys.path.insert(0, str(Path(__file__).resolve().parent))
import p4_lib as L  # noqa: E402

OUT = L.OUT / "T09"


def save_svg(fig, path):
    import matplotlib
    matplotlib.rcParams["svg.hashsalt"] = "dms-p4"
    fig.savefig(path, format="svg", metadata={"Date": None}, bbox_inches="tight")


def main() -> int:
    import matplotlib
    matplotlib.use("Agg")
    matplotlib.rcParams["svg.fonttype"] = "none"
    matplotlib.rcParams["font.family"] = ["DejaVu Sans"]   # bundled with matplotlib: same metrics on any machine
    import matplotlib.pyplot as plt
    import numpy as np
    import pandas as pd
    wide, h = L.cohort_matrix()
    wide = wide.dropna(axis=1)
    sd = wide.std(ddof=0)
    wide = wide.loc[:, sd > 0]
    z = (wide - wide.mean()) / wide.std(ddof=0)
    U, S, Vt = np.linalg.svd(z.values, full_matrices=False)
    for k in range(Vt.shape[0]):
        j = np.argmax(np.abs(Vt[k]))
        if Vt[k, j] < 0:
            Vt[k] *= -1
            U[:, k] *= -1
    var = S ** 2 / (S ** 2).sum()
    co = L.cohorts(L.load()).set_index("cohort")
    meta = h.drop_duplicates("measure").set_index("measure")
    coords = pd.DataFrame({"cohort": z.index, "label": [co.loc[c, "label"] for c in z.index],
                           "dimension": [co.loc[c, "dimension"] for c in z.index],
                           "pc1": np.round(U[:, 0] * S[0], 4), "pc2": np.round(U[:, 1] * S[1], 4)})
    load = pd.DataFrame({"measure": z.columns, "gate": [meta.loc[m, "gate"] for m in z.columns],
                         "pc1": np.round(Vt[0], 4), "pc2": np.round(Vt[1], 4)})
    expl = pd.DataFrame({"component": [f"pc{k + 1}" for k in range(min(10, len(var)))],
                         "explained_variance": np.round(var[:10], 4), "cumulative": np.round(np.cumsum(var[:10]), 4)})
    L.write_csv(coords, OUT / "cohort_coordinates.csv")
    L.write_csv(load, OUT / "measure_loadings.csv")
    L.write_csv(expl, OUT / "explained_variance.csv")
    fig, ax = plt.subplots(figsize=(9, 7))
    ax.scatter(coords.pc1, coords.pc2, color="black", s=14)
    for x in coords.itertuples():
        ax.annotate(f"{x.label} ({x.dimension.replace('D-', '')})", (x.pc1, x.pc2), fontsize=5, xytext=(2, 2),
                    textcoords="offset points")
    top = load.assign(r=np.hypot(load.pc1, load.pc2)).sort_values(["r", "measure"], ascending=[False, True]).head(10)
    scale = 0.9 * min(np.abs(coords.pc1).max(), np.abs(coords.pc2).max()) / max(top.r.max(), 1e-9)
    for x in top.itertuples():
        ax.arrow(0, 0, x.pc1 * scale, x.pc2 * scale, color="0.5", width=0.01, head_width=0.15, length_includes_head=True)
        ax.annotate(x.measure, (x.pc1 * scale, x.pc2 * scale), fontsize=6, color="0.3")
    ax.axhline(0, color="0.85", lw=0.5); ax.axvline(0, color="0.85", lw=0.5)
    ax.set_xlabel(f"component 1 ({var[0]:.0%} of variation)"); ax.set_ylabel(f"component 2 ({var[1]:.0%})")
    ax.set_title("Map of cohorts by their answers; arrows = the 10 questions that pull hardest (ecological)", fontsize=8)
    save_svg(fig, OUT / "cohort_map.svg")
    md = ["# T09 results — map of cohorts × questions", "", "Generated by `scripts/p4_t09_cohort_map.py`. Principal components "
          f"of {z.shape[0]} usable cohorts × {z.shape[1]} standardised headline measures. Ecological: cohorts overlap.", "",
          f"Component 1 explains {var[0]:.0%} of the variation between cohorts; component 2 {var[1]:.0%}; "
          f"together {var[:2].sum():.0%}.", ""]
    for k, col in enumerate(["pc1", "pc2"]):
        lo = load.sort_values([col, "measure"], ascending=[True, True], kind="stable")
        cs = coords.sort_values([col, "cohort"], kind="stable")
        md += [f"## Component {k + 1}", "",
               "Questions pulling positive: " + "; ".join(f"{m.measure} ({m.gate})" for m in lo.tail(4).iloc[::-1].itertuples()) + ".",
               "Questions pulling negative: " + "; ".join(f"{m.measure} ({m.gate})" for m in lo.head(4).itertuples()) + ".",
               "Cohorts at the positive end: " + "; ".join(f"{c.label} ({c.dimension.replace('D-', '')})" for c in cs.tail(4).iloc[::-1].itertuples()) + ".",
               "Cohorts at the negative end: " + "; ".join(f"{c.label} ({c.dimension.replace('D-', '')})" for c in cs.head(4).itertuples()) + ".", ""]
    md += ["Files: `cohort_coordinates.csv`, `measure_loadings.csv`, `explained_variance.csv`, `cohort_map.svg`.", ""]
    (OUT / "summary.md").write_text("\n".join(md), encoding="utf-8")
    print(f"T09 pc1={var[0]:.3f} pc2={var[1]:.3f}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
