#!/usr/bin/env python3
"""T01 — gate profile: every result, keyed by gate, plus a one-line reading per question for All respondents.

Reads 03_schema/examples/full_study.xml through p4_lib. Writes 04_analytics_library/outputs/T01/.
Usage: python3 -I scripts/p4_t01_gate_profile.py
"""
import sys
from pathlib import Path

sys.dont_write_bytecode = True
sys.path.insert(0, str(Path(__file__).resolve().parent))
import p4_lib as L  # noqa: E402

OUT = L.OUT / "T01"
ALL = "C-L-ALL-RESPONDENTS"


def main() -> int:
    d = L.load()
    r = L.results(d)
    r["gate_order"] = r.gate.map(L.GATE_ORDER.index)
    prof = r.sort_values(["gate_order", "thread", "item", "cohort", "option"], kind="stable").drop(columns="gate_order")
    L.write_csv(prof, OUT / "gate_profile.csv")
    m = L.measures()
    a = m[(m.cohort == ALL)]
    it = L.items(d).set_index("item")
    lines = []
    for item in prof[prof.cohort == ALL].item.drop_duplicates():
        g = a[a.item == item]
        if g.empty:
            continue
        head = g[(g.kind == "summary") & (g.role == "headline")]
        if not head.empty:
            x = head.iloc[0]; reading = f"{x.measure}: {x.value:.2f}"
        elif (g.kind == "selection").any():
            x = g[g.kind == "selection"].iloc[0]; reading = f"selected by {x.value:.2f}"
        else:
            x = g[g.kind == "option"].sort_values("value", ascending=False).iloc[0]
            reading = f"most chosen: '{x.label}' {x.value:.2f}"
        lines.append({"gate": x.gate, "thread": x.thread, "item": item,
                      "wording": (it.loc[item, "label"] or it.loc[item, "stem"])[:120], "reading_all": reading,
                      "base_all": x.base})
    import pandas as pd
    s = pd.DataFrame(lines)
    s["gate_order"] = s.gate.map(L.GATE_ORDER.index)
    s = s.sort_values(["gate_order", "thread", "item"], kind="stable").drop(columns="gate_order")
    L.write_csv(s, OUT / "gate_summary.csv")
    md = ["# T01 results — gate profile", "", "Generated by `scripts/p4_t01_gate_profile.py`. All respondents (n = 319); "
          "headline measure where one is defined, else the share selecting, else the most chosen option.", "",
          f"`gate_profile.csv`: {len(prof)} results ({int(prof.usable.sum())} usable at n ≥ 25).", ""]
    for gate, g in s.groupby(s.gate.map(L.GATE_ORDER.index), sort=True):
        md += [f"## {L.GATE_ORDER[gate]}", "", "| Item | Wording | Reading |", "|---|---|---|"]
        for x in g.itertuples():
            md.append(f"| {x.item} | {x.wording.replace('|', '/')} | {x.reading_all.replace('|', '/')} |")
        md.append("")
    (OUT / "summary.md").write_text("\n".join(md), encoding="utf-8")
    print(f"T01 results={len(prof)} items={len(s)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
