#!/usr/bin/env python3
"""p5_build_coding_frame.py — coding_frame.md from coding_frame.csv (authored) and the asymmetry lexicon.

The lexicon layer is generated from 01_instrument_reconstruction/lexicon_entries.csv (one code per concept,
L01–L26), so the frame and the lexicon cannot drift. Checks: unique codes; every code has a definition and
include rule; in v1 or later, every code has at least one example (GOVERNANCE §5 P5).
Usage: python3 -I scripts/p5_build_coding_frame.py [--require-examples]
"""
import csv
import sys
from collections import OrderedDict
from pathlib import Path

FRAME = Path("05_open_ended/coding_frame.csv")
LEX = Path("01_instrument_reconstruction/lexicon_entries.csv")
OUT = Path("05_open_ended/coding_frame.md")
LAYERS = OrderedDict([("notcodable", "Not codable (checked first)"), ("gate", "Gate (M10)"), ("behaviour", "Behaviour (M2–M4)"),
                      ("servqual", "SERVQUAL dimension (M6)"), ("meansend", "Means-end level (M7)"),
                      ("attribution", "Attribution (M8)"), ("valence", "Valence (M13 check)"), ("lexicon", "Lexicon concept (M11)")])
FIELDS = ["layer", "code", "label", "definition", "include", "exclude", "example", "origin", "source", "version"]


def rows():
    frame = list(csv.DictReader(FRAME.open(encoding="utf-8")))
    lex_examples = {r["code"]: r for r in frame if r["layer"] == "lexicon"}
    out = [r for r in frame if r["layer"] != "lexicon"]
    for e in csv.DictReader(LEX.open(encoding="utf-8")):
        r = lex_examples.get(e["entry_id"], {})
        out.append({"layer": "lexicon", "code": e["entry_id"], "label": e["concept"],
                    "definition": f"The answer expresses the lexicon concept '{e['concept']}' ({e['group']})"
                                  + (f"; gap: {e['gap']}" if e["gap"] else ""),
                    "include": r.get("include") or f"decision-maker wording for: {e['concept'].lower()}",
                    "exclude": r.get("exclude", ""), "example": r.get("example", ""),
                    "origin": r.get("origin") or "deductive", "source": r.get("source") or "M11 asymmetry_lexicon",
                    "version": r.get("version") or "v0"})
    return out


def main() -> int:
    need_examples = "--require-examples" in sys.argv
    rs = rows()
    errs = []
    seen = set()
    for r in rs:
        if r["code"] in seen:
            errs.append(f"duplicate code {r['code']}")
        seen.add(r["code"])
        if r["layer"] not in LAYERS:
            errs.append(f"{r['code']}: unknown layer {r['layer']}")
        if not r["definition"] or not r["include"]:
            errs.append(f"{r['code']}: definition or include rule missing")
        if need_examples and not r["example"]:          # every layer, lexicon included (GOVERNANCE §5 P5)
            errs.append(f"{r['code']}: no example")
        if need_examples and not r["exclude"]:
            errs.append(f"{r['code']}: no exclude rule")
    if errs:
        for e in errs:
            print("ERROR:", e, file=sys.stderr)
        return 2
    version = max(r["version"] for r in rs)
    L = ["# Coding Frame", "", f"Generated by `scripts/p5_build_coding_frame.py` from `coding_frame.csv` and the asymmetry lexicon. "
         f"Version: **{version}**. Do not edit by hand.", "",
         "Each answer is coded on every layer that applies. An answer may carry several codes in a layer; one is marked "
         "primary (Scott, D5-3). Not-codable answers get only an N- code. All codes are INFERRED (assigned by Claude). "
         "Methods: `methods.md`.", "",
         "| Layer | Codes | Deductive | Inductive |", "|---|---|---|---|"]
    for k, name in LAYERS.items():
        lr = [r for r in rs if r["layer"] == k]
        L.append(f"| {name} | {len(lr)} | {sum(r['origin'] == 'deductive' for r in lr)} | {sum(r['origin'] == 'inductive' for r in lr)} |")
    L += ["", "## Coding rules", "",
          "1. Check not-codable first. A not-codable answer gets one N- code and nothing else.",
          "2. Every codable answer gets at least one gate and one valence; the other layers where they apply.",
          "3. Several codes per layer are allowed; the first is primary — the most central idea of the answer.",
          "4. Behaviour codes are dimensions with a polarity: + when the decision-maker experienced it well (or names it as what they want), − when badly (e.g. 'pushy' = B-CUSTOMER-FIRST −; 'doesn't listen' = B-LISTENS −).",
          "5. Gate by stage: outreach and contact → ACCESS; right message to the right person → TARGET; the meeting and the salesperson's conduct in it → AGREE; the solution, fit and path to value → VISION; price, ROI, risk, justification → CASE; delivery, support and the account after the decision → RELATIONSHIP; general traits with no stage → NONE.",
          "6. Q21 (what differentiates a vendor) gives criteria: valence V-NEUTRAL unless the answer itself praises or criticises vendors; always lexicon L03, plus any specific concept.",
          "7. Q22 and Q24 describe the best; Q23 and Q25 the worst. Code what the answer says — valence is usually + for best and − for worst, but not always.",
          "8. Q24 and Q25 (primary contact): gate RELATIONSHIP and lexicon L25, unless the reason is about a selling stage. A role with no reason is N-ROLE-ONLY; vendor names with no reason are N-NAMES-ONLY.",
          "9. 'Please specify' answers are coded in the context of their parent question (Q8 preparation, Q12 material, Q13 meeting, Q15 pulling back, Q19 shaping a plan, Q7 taking a meeting, Q1 strategic qualities, Q18 case materials). Amounts and role descriptions are N-VALUE.",
          "10. Attribution: whom the answer credits or blames. Means-end: every level the answer reaches (attribute, consequence, value)."]
    for k, name in LAYERS.items():
        L += ["", f"## {name}", "", "| Code | Label | Definition | Include | Exclude | Example | Origin |", "|---|---|---|---|---|---|---|"]
        for r in [r for r in rs if r["layer"] == k]:
            cells = [r["code"], r["label"], r["definition"], r["include"], r["exclude"],
                     f"“{r['example']}”" if r["example"] else "", f"{r['origin']} ({r['source']})"]
            L.append("| " + " | ".join(c.replace("|", "/") for c in cells) + " |")
    L.append("")
    OUT.write_text("\n".join(L), encoding="utf-8")
    print(f"codes={len(rs)} version={version}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
