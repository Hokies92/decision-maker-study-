#!/usr/bin/env python3
"""T06 — thread network: how the 37 questions connect through the links the instrument defines.

Builds the thread graph from Graph/Link in full_study.xml (item endpoints folded to their thread; group and
variable endpoints and self-loops dropped). Two views:
    all        every structural link type
    questions  without screener breakouts (breakout_of, relates_to): question-to-question structure
Metrics per thread: degree, distinct neighbours, betweenness; communities (greedy modularity) in the
questions view, compared with Scott's grouping. Writes 04_analytics_library/outputs/T06/.
Usage: python3 -I scripts/p4_t06_thread_network.py
"""
import sys
from pathlib import Path

sys.dont_write_bytecode = True
sys.path.insert(0, str(Path(__file__).resolve().parent))
import p4_lib as L  # noqa: E402

OUT = L.OUT / "T06"
SCREENER_TYPES = {"breakout_of", "relates_to"}


def save_svg(fig, path):
    import matplotlib
    matplotlib.rcParams["svg.hashsalt"] = "dms-p4"
    fig.savefig(path, format="svg", metadata={"Date": None}, bbox_inches="tight")


def graph(links, it_thread, threads, gate_of, exclude=frozenset()):
    import networkx as nx
    G = nx.Graph()
    for t in threads:
        G.add_node(t, gate=gate_of[t], label=t[2:])
    for l in links.itertuples():
        if l.type in exclude or l.type == "in_group":
            continue
        a = it_thread.get(l.source, l.source)
        b = it_thread.get(l.target, l.target)
        if a not in G or b not in G or a == b:
            continue
        if G.has_edge(a, b):
            G[a][b]["links"] += 1
            G[a][b]["types"] = ";".join(sorted(set(G[a][b]["types"].split(";")) | {l.type}))
        else:
            G.add_edge(a, b, links=1, types=l.type)
    return G


def main() -> int:
    import matplotlib
    matplotlib.use("Agg")
    matplotlib.rcParams["svg.fonttype"] = "none"
    matplotlib.rcParams["font.family"] = ["DejaVu Sans"]   # bundled with matplotlib: same metrics on any machine
    import matplotlib.pyplot as plt
    import networkx as nx
    import pandas as pd
    d = L.load()
    lk = L.links(d)
    it = L.items(d)
    it_thread = dict(zip(it.item, it.thread))
    threads = list(dict.fromkeys(it.thread))
    gate_of = L._gate_of_thread(d)[0]
    views = {"all": graph(lk, it_thread, threads, gate_of),
             "questions": graph(lk, it_thread, threads, gate_of, exclude=SCREENER_TYPES)}
    rows = []
    for name, G in views.items():
        bc = nx.betweenness_centrality(G, normalized=True)
        for t in threads:
            rows.append({"view": name, "thread": t, "gate": gate_of[t], "neighbours": G.degree(t),
                         "links": int(sum(e["links"] for _, _, e in G.edges(t, data=True))),
                         "betweenness": round(bc[t], 4)})
    metrics = pd.DataFrame(rows)
    L.write_csv(metrics, OUT / "thread_metrics.csv")
    Q = views["questions"]
    comms = nx.algorithms.community.greedy_modularity_communities(Q, weight="links")
    comms = sorted([sorted(c) for c in comms], key=lambda c: (-len(c), c))
    crow = [{"community": k + 1, "thread": t, "gate": gate_of[t]} for k, c in enumerate(comms) for t in c]
    cdf = pd.DataFrame(crow)
    L.write_csv(cdf, OUT / "communities.csv")
    xtab = pd.crosstab(cdf.community, cdf.gate)
    L.write_csv(xtab.reset_index(), OUT / "communities_vs_gates.csv")
    mod = nx.algorithms.community.modularity(Q, [set(c) for c in comms], weight="links")
    gate_groups = {}
    for t in threads:
        gate_groups.setdefault(gate_of[t], set()).add(t)
    mod_gates = nx.algorithms.community.modularity(Q, list(gate_groups.values()), weight="links")
    for name, G in views.items():
        nx.write_graphml(G, OUT / f"thread_network_{name}.graphml")
    pos = nx.spring_layout(Q, seed=7, weight="links")
    shade = {g: str(s) for g, s in zip(["TARGET", "baseline", "ACCESS", "AGREE", "VISION", "CASE", "crossGate"],
                                       [0.95, 0.85, 0.7, 0.55, 0.4, 0.25, 0.1])}
    fig, ax = plt.subplots(figsize=(8, 6))
    nx.draw_networkx_edges(Q, pos, ax=ax, edge_color="0.75", width=[0.5 + 0.5 * Q[u][v]["links"] for u, v in Q.edges()])
    nx.draw_networkx_nodes(Q, pos, ax=ax, node_color=[shade[gate_of[t]] for t in Q.nodes()], edgecolors="black",
                           node_size=[120 + 60 * Q.degree(t) for t in Q.nodes()])
    nx.draw_networkx_labels(Q, pos, ax=ax, labels={t: t[2:] for t in Q.nodes()}, font_size=6)
    ax.set_title("Question network (screener breakouts removed); shade = gate, light → dark: Target → Case", fontsize=8)
    ax.axis("off")
    save_svg(fig, OUT / "thread_network_questions.svg")
    top = metrics[metrics.view == "questions"].sort_values(["betweenness", "thread"], ascending=[False, True]).head(8)
    md = ["# T06 results — thread network", "", "Generated by `scripts/p4_t06_thread_network.py` from the links in "
          "`full_study.xml`. Structural links only (defined by the instrument); statistical links are T07.", "",
          f"Views: all links — {views['all'].number_of_edges()} thread pairs; questions only (screener breakouts removed) — "
          f"{Q.number_of_edges()} thread pairs, {nx.number_of_isolates(Q)} isolated threads.", "",
          "## Most central questions (questions view, betweenness)", "", "| Thread | Gate | Neighbours | Betweenness |", "|---|---|---|---|"]
    for x in top.itertuples():
        md.append(f"| {x.thread[2:]} | {x.gate} | {x.neighbours} | {x.betweenness:.3f} |")
    md += ["", "## Communities vs Scott's gates", "", f"{len(comms)} communities (greedy modularity, modularity {mod:.3f}); "
           f"Scott's grouping as a partition of the same graph: modularity {mod_gates:.3f}. "
           "Higher modularity = groups that are more tightly linked inside than between.", "",
           "| Community | Threads |", "|---|---|"]
    for k, c in enumerate(comms):
        md.append(f"| {k + 1} | " + ", ".join(f"{t[2:]} ({gate_of[t]})" for t in c) + " |")
    md += ["", "Files: `thread_metrics.csv`, `communities.csv`, `communities_vs_gates.csv`, "
           "`thread_network_all.graphml`, `thread_network_questions.graphml`, `thread_network_questions.svg`.", ""]
    (OUT / "summary.md").write_text("\n".join(md), encoding="utf-8")
    print(f"T06 edges all={views['all'].number_of_edges()} questions={Q.number_of_edges()} communities={len(comms)} "
          f"mod={mod:.3f} mod_gates={mod_gates:.3f}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
