#!/usr/bin/env python3
"""p2_build_coverage_matrix.py — how many respondents stand behind every cohort × item.

Inputs (read-only): 02_data_inventory/results.csv, 01_instrument_reconstruction/cohorts.csv
Outputs: 02_data_inventory/coverage_matrix.csv (long: cohort × item → base) and coverage_matrix.md

Base n per cohort × item comes from the table base rows (P2.S01). Minimum n = 25 (Scott,
2026-10-28): a cell below it is flagged — shown, never used for comparative claims.
The function × level intersection (the only one tabulated) gets its own table.

Usage: python3 -I scripts/p2_build_coverage_matrix.py
"""

from __future__ import annotations

import csv
import statistics
import sys
from collections import defaultdict
from pathlib import Path

OD, RD = Path("02_data_inventory"), Path("01_instrument_reconstruction")
OUT_CSV, OUT_MD = OD / "coverage_matrix.csv", OD / "coverage_matrix.md"
MIN_N = 25
FIELDS = ["cohort_id", "dimension_id", "cohort_label", "cohort_n", "item_id", "base_n", "flag", "sheet"]


def main() -> int:
    cohorts = {c["cohort_id"]: c for c in csv.DictReader((RD / "cohorts.csv").open(encoding="utf-8"))}
    cells = {}
    for r in csv.DictReader((OD / "results.csv").open(encoding="utf-8")):
        if r["value_status"] != "value":
            continue
        key = (r["cohort_id"], r["item_id"])
        if key not in cells or r["sheet"] == "Industry 7":
            cells[key] = (r["base_n"], r["sheet"])
    rows, errors = [], []
    for (cid, item), (base, sheet) in sorted(cells.items()):
        c = cohorts[cid]
        if base == "":
            errors.append(f"{cid} × {item}: no base"); continue
        b = int(base)
        if b > int(c["n"]):
            errors.append(f"{cid} × {item}: base {b} > cohort n {c['n']}")
        rows.append({"cohort_id": cid, "dimension_id": c["dimension_id"], "cohort_label": c["label"],
                     "cohort_n": c["n"], "item_id": item, "base_n": b,
                     "flag": "ok" if b >= MIN_N else f"below {MIN_N}", "sheet": sheet})
    if errors:
        for e in errors[:20]:
            print("ERROR:", e, file=sys.stderr)
        return 2
    with OUT_CSV.open("w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=FIELDS, lineterminator="\n")
        w.writeheader(); w.writerows(rows)

    per = defaultdict(list)
    for r in rows:
        per[r["cohort_id"]].append(r["base_n"])
    below = [r for r in rows if r["flag"] != "ok"]
    order = [c for c in cohorts if c in per]
    L = ["# Coverage Matrix", "", "Generated by `scripts/p2_build_coverage_matrix.py`. Full detail: `coverage_matrix.csv` "
         "(one row per cohort × item).", "",
         f"**{len(rows)} cohort × item cells**; **{len(below)} below n = {MIN_N}** "
         f"({len(below) / len(rows):.0%}). Below-minimum cells are shown but never used for comparative claims.", "",
         "## Function × level (the only tabulated intersection)", "",
         "| Function | Level | n | Items | Smallest item base | Flag |", "|---|---|---|---|---|---|"]
    for dim, fn in (("D-LEVEL-IT", "IT (ITDM)"), ("D-LEVEL-BUS", "Business (BDM)")):
        for cid in order:
            c = cohorts[cid]
            if c["dimension_id"] == dim:
                b = per[cid]
                L.append(f"| {fn} | {c['label']} | {c['n']} | {len(b)} | {min(b)} | "
                         f"{'ok' if int(c['n']) >= MIN_N else f'below {MIN_N}'} |")
    L += ["", "## Every tabulated cohort", "",
          "| Cohort | Dimension | n | Items | Median item base | Smallest item base | Items below 25 |",
          "|---|---|---|---|---|---|---|"]
    for cid in order:
        c, b = cohorts[cid], per[cid]
        L.append(f"| {c['label']} | {c['dimension_id']} | {c['n']} | {len(b)} | {int(statistics.median(b))} | {min(b)} | "
                 f"{sum(1 for x in b if x < MIN_N)} |")
    L.append("")
    OUT_MD.write_text("\n".join(L), encoding="utf-8")
    print(f"cells={len(rows)} below_min={len(below)} cohorts={len(per)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
