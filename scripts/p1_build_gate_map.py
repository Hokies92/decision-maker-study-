#!/usr/bin/env python3
"""p1_build_gate_map.py — assign every question item to a gate.

Inputs (read-only):
    01_instrument_reconstruction/question_map.csv   (P1.S02, generated)
    01_instrument_reconstruction/gate_rules.csv     (authored, INFERRED)
Outputs:
    01_instrument_reconstruction/gate_map.csv       one row per item
    01_instrument_reconstruction/gate_map.md        readable map, grouped by gate

Gates (design_intent.md §2.2): Target, Access, Agree, Vision, Case.
Outside the gates: Terminal (contract/spend outcomes, outside the value communication
process), Cross-gate (spans several gates; resolved later, e.g. by Phase 5 coding),
None (attention check, don't know).

Rule precedence: an `item` rule overrides its thread's `thread` rule. Every item must
resolve; every rule must match an existing thread or item.

Usage: python3 -I scripts/p1_build_gate_map.py
"""

from __future__ import annotations

import csv
import sys
from collections import defaultdict
from pathlib import Path

QMAP = Path("01_instrument_reconstruction/question_map.csv")
RULES = Path("01_instrument_reconstruction/gate_rules.csv")
OUT_CSV = Path("01_instrument_reconstruction/gate_map.csv")
OUT_MD = Path("01_instrument_reconstruction/gate_map.md")

GATES = ["Target", "Access", "Agree", "Vision", "Case"]
OUTSIDE = ["Terminal", "Cross-gate", "None"]
VALID = set(GATES + OUTSIDE)
FIELDS = ["thread_id", "item_id", "item_role", "question_type", "primary_gate", "facet",
          "secondary_gate", "rule_scope", "rationale", "provenance", "wording"]


def wording(it: dict) -> str:
    label, stem = it["item_label"].strip(), it["stem"].strip()
    text = f"{label} — {stem}" if label and stem else (label or stem)
    return text if len(text) <= 140 else text[:137] + "…"


def main() -> int:
    items = list(csv.DictReader(QMAP.open(encoding="utf-8")))
    rules = list(csv.DictReader(RULES.open(encoding="utf-8")))
    threads = {i["thread_id"] for i in items}
    ids = {i["item_id"] for i in items}

    by_thread, by_item, errors = {}, {}, []
    for r in rules:
        for g in (r["primary_gate"], r["secondary_gate"]):
            if g and g not in VALID:
                errors.append(f"unknown gate '{g}' in rule {r['id']}")
        if r["scope"] == "thread":
            (by_thread.__setitem__(r["id"], r) if r["id"] in threads
             else errors.append(f"thread rule for unknown thread {r['id']}"))
        elif r["scope"] == "item":
            (by_item.__setitem__(r["id"], r) if r["id"] in ids
             else errors.append(f"item rule for unknown item {r['id']}"))
        else:
            errors.append(f"bad scope '{r['scope']}' in rule {r['id']}")

    out = []
    for it in items:
        rule = by_item.get(it["item_id"]) or by_thread.get(it["thread_id"])
        if not rule:
            errors.append(f"no rule for {it['item_id']} ({it['thread_id']})")
            continue
        out.append({
            "thread_id": it["thread_id"], "item_id": it["item_id"],
            "item_role": it["item_role"], "question_type": it["question_type"],
            "primary_gate": rule["primary_gate"], "facet": rule["facet"],
            "secondary_gate": rule["secondary_gate"], "rule_scope": rule["scope"],
            "rationale": rule["rationale"], "provenance": "INFERRED", "wording": wording(it),
        })
    if errors:
        for e in errors:
            print("ERROR:", e, file=sys.stderr)
        return 2

    with OUT_CSV.open("w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=FIELDS, lineterminator="\n")
        w.writeheader()
        w.writerows(out)

    grouped = defaultdict(list)
    for r in out:
        grouped[r["primary_gate"]].append(r)
    sec = defaultdict(int)
    for r in out:
        if r["secondary_gate"]:
            sec[r["secondary_gate"]] += 1

    lines = [
        "# Gate Map — every question item",
        "",
        "Generated by `scripts/p1_build_gate_map.py` from `gate_rules.csv`. Do not edit by hand.",
        "",
        "All assignments are `INFERRED` (Claude), pending Scott's review. Wording is `VERBATIM` "
        "from `question_map.csv` (label — stem), shortened where long.",
        "",
        "**Gates** (Scott, `design_intent.md` §2.2): Target · Access · Agree · Vision · Case. "
        "**Outside the gates:** Terminal (contract/spend — outside the value communication process), "
        "Cross-gate (spans gates; resolved later), None (attention check, don't know).",
        "",
        "## Summary",
        "",
        "| Gate | Items (primary) | Also touches (secondary) |",
        "|---|---|---|",
    ]
    for g in GATES + OUTSIDE:
        lines.append(f"| {g} | {len(grouped.get(g, []))} | {sec.get(g, 0)} |")
    lines += ["", f"Total items: {len(out)}", ""]

    for g in GATES + OUTSIDE:
        rows = grouped.get(g, [])
        if not rows:
            continue
        lines += [f"## {g}", "", "| Item | Facet | Also | Wording | Why |", "|---|---|---|---|---|"]
        for r in rows:
            wtxt = r["wording"].replace("|", "\\|")
            why = r["rationale"].replace("|", "\\|")
            tag = " *(derived)*" if r["item_role"] == "derived" else (
                " *(attention check)*" if r["item_role"] == "attention_check" else "")
            lines.append(f"| {r['item_id']}{tag} | {r['facet']} | {r['secondary_gate'] or ''} | {wtxt} | {why} |")
        lines.append("")
    OUT_MD.write_text("\n".join(lines), encoding="utf-8")

    print(f"items={len(out)} → {OUT_CSV}, {OUT_MD}")
    print("primary:", {g: len(grouped.get(g, [])) for g in GATES + OUTSIDE})
    print("secondary:", dict(sec))
    return 0


if __name__ == "__main__":
    sys.exit(main())
