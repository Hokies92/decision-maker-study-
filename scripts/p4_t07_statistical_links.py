#!/usr/bin/env python3
"""T07 — statistical thread links: which questions move together across cohorts.

For every pair of headline measures from different threads, the Spearman rank correlation of their values
across usable cohorts (p4_lib.cohort_matrix: n ≥ 25, base ≥ 25; All respondents excluded). Pairs with
|rho| ≥ 0.6 are candidate 'covaries_with' links — a new, statistical link type (not yet in the schema).
ECOLOGICAL: cohorts are groups, not people, and they overlap (e.g. a country and its region; a function and
its levels). Writes 04_analytics_library/outputs/T07/.
Usage: python3 -I scripts/p4_t07_statistical_links.py
"""
import sys
from pathlib import Path

sys.dont_write_bytecode = True
sys.path.insert(0, str(Path(__file__).resolve().parent))
import p4_lib as L  # noqa: E402

OUT = L.OUT / "T07"
THRESHOLD = 0.6
MIN_COHORTS = 20


def main() -> int:
    import itertools
    import networkx as nx
    import pandas as pd
    from scipy.stats import spearmanr
    wide, h = L.cohort_matrix(MIN_COHORTS)
    meta = h.drop_duplicates("measure").set_index("measure")
    rows = []
    for a, b in itertools.combinations(wide.columns, 2):
        if meta.loc[a, "thread"] == meta.loc[b, "thread"]:
            continue
        x = wide[[a, b]].dropna()
        if len(x) < MIN_COHORTS or x[a].nunique() < 2 or x[b].nunique() < 2:
            continue
        rho = spearmanr(x[a], x[b]).statistic
        rows.append({"measure_a": a, "thread_a": meta.loc[a, "thread"], "gate_a": meta.loc[a, "gate"],
                     "measure_b": b, "thread_b": meta.loc[b, "thread"], "gate_b": meta.loc[b, "gate"],
                     "cohorts": len(x), "rho": round(float(rho), 4)})
    df = pd.DataFrame(rows)
    df["candidate_link"] = df.rho.abs() >= THRESHOLD
    df["cross_gate"] = df.gate_a != df.gate_b
    df["link_type"] = "covaries_with"
    df["provenance"] = "INFERRED"
    df["caveat"] = "ecological: across overlapping cohorts, not individuals"
    L.write_csv(df, OUT / "measure_correlations.csv")
    cand = df[df.candidate_link].sort_values(["rho", "measure_a", "measure_b"], ascending=[False, True, True], kind="stable")
    L.write_csv(cand, OUT / "candidate_links.csv")
    G = nx.Graph()
    for m in wide.columns:
        G.add_node(m, thread=meta.loc[m, "thread"], gate=meta.loc[m, "gate"])
    for x in cand.itertuples():
        G.add_edge(x.measure_a, x.measure_b, rho=x.rho, link_type="covaries_with", caveat="ecological")
    nx.write_graphml(G, OUT / "statistical_links.graphml")
    gate_pairs = cand.assign(pair=cand.apply(lambda r: " – ".join(sorted([r.gate_a, r.gate_b])), axis=1)) \
        .groupby("pair").size().sort_values(ascending=False)
    md = ["# T07 results — statistical thread links", "", "Generated by `scripts/p4_t07_statistical_links.py`.", "",
          "**Ecological caveat:** each correlation is across cohorts (groups), and the cohorts overlap. A strong correlation "
          "says that groups high on one measure tend to be high on the other — not that the same people answer both ways.", "",
          f"{wide.shape[1]} headline measures × {wide.shape[0]} usable cohorts; {len(df)} pairs from different threads; "
          f"{len(cand)} with |rho| ≥ {THRESHOLD} ({int(cand.cross_gate.sum())} of them across gates).", "",
          "## Candidate links by gate pair", "", "| Gates | Links |", "|---|---|"]
    for k, v in gate_pairs.items():
        md.append(f"| {k} | {v} |")
    md += ["", "## Strongest cross-gate links", "", "| A | B | Cohorts | rho |", "|---|---|---|---|"]
    xg = cand[cand.cross_gate].reindex(cand[cand.cross_gate].rho.abs().sort_values(ascending=False, kind="stable").index).head(12)
    for x in xg.itertuples():
        md.append(f"| {x.measure_a} ({x.gate_a}) | {x.measure_b} ({x.gate_b}) | {x.cohorts} | {x.rho:+.2f} |")
    md += ["", "Files: `measure_correlations.csv`, `candidate_links.csv`, `statistical_links.graphml`.", ""]
    (OUT / "summary.md").write_text("\n".join(md), encoding="utf-8")
    print(f"T07 pairs={len(df)} candidates={len(cand)} cross_gate={int(cand.cross_gate.sum())}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
