#!/usr/bin/env python3
"""p1_check_review.py — confirm every open inference from P1.S09 has Scott's decision.

Inputs: 01_instrument_reconstruction/inferred_for_review.csv (generated, P1.S09)
        01_instrument_reconstruction/review_decisions.csv   (authored, Scott's decisions)
Output: 01_instrument_reconstruction/review_summary.md
Exit 2 if any review item lacks a decision or a decision matches no review item.

Usage: python3 -I scripts/p1_check_review.py
"""
import csv
import sys
from collections import Counter
from pathlib import Path

RD = Path("01_instrument_reconstruction")
items = list(csv.DictReader((RD / "inferred_for_review.csv").open(encoding="utf-8")))
dec = list(csv.DictReader((RD / "review_decisions.csv").open(encoding="utf-8")))
key = lambda r: (r["file"], r["id"])
ik, dk = {key(r) for r in items}, {key(r) for r in dec}
missing, extra = sorted(ik - dk), sorted(dk - ik)
bad = [r["n"] for r in dec if r["decision"] not in ("approved", "rejected", "changed")]
counts = Counter((r["file"], r["decision"]) for r in dec)
ok = not missing and not extra and not bad
lines = ["# Designer Review — P1.S10", "", "Generated by `scripts/p1_check_review.py`.", "",
         f"**Result: {'every inference decided' if ok else 'INCOMPLETE'}** — {len(dec)} decisions for {len(items)} review items.", "",
         "| File | Decision | Items |", "|---|---|---|"]
for (f, d), n in sorted(counts.items()):
    lines.append(f"| {f} | {d} | {n} |")
lines += ["", f"Missing decisions: {missing or 'none'}. Decisions without a review item: {extra or 'none'}.", "",
          "Status after review: `INFERRED — confirmed by Scott` (Claude's inference, approved by Scott; not his recollection, "
          "so not re-tagged `RECALL_DESIGNER`).", ""]
(RD / "review_summary.md").write_text("\n".join(lines), encoding="utf-8")
print("PASS" if ok else "FAIL", len(dec), "decisions")
sys.exit(0 if ok else 2)
