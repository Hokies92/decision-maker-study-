#!/usr/bin/env python3
"""T02 — summary measures: every approved summary variable computed for every cohort.

Reads full_study.xml through p4_lib.measures(). Writes 04_analytics_library/outputs/T02/.
Usage: python3 -I scripts/p4_t02_summary_measures.py
"""
import sys
from pathlib import Path

sys.dont_write_bytecode = True
sys.path.insert(0, str(Path(__file__).resolve().parent))
import p4_lib as L  # noqa: E402

OUT = L.OUT / "T02"
ALL = "C-L-ALL-RESPONDENTS"


def main() -> int:
    m = L.measures()
    s = m[m.kind == "summary"].copy()
    s["gate_order"] = s.gate.map(L.GATE_ORDER.index)
    s = s.sort_values(["gate_order", "measure", "cohort"], kind="stable").drop(columns=["gate_order", "kind"])
    L.write_csv(s, OUT / "summary_measures.csv")
    a = s[(s.cohort == ALL) & (s.role == "headline")].sort_values("value", ascending=False, kind="stable")
    md = ["# T02 results — summary measures", "", "Generated by `scripts/p4_t02_summary_measures.py`. "
          f"{s.measure.nunique()} summary variables × cohorts = {len(s)} values ({int(s.usable.sum())} usable at n ≥ 25). "
          "Definitions approved by Scott (P4.S01). Below: headline measures for All respondents, highest first.", "",
          "| Gate | Measure | Value |", "|---|---|---|"]
    for x in a.itertuples():
        md.append(f"| {x.gate} | {x.measure} — {x.label} | {x.value:.2f} |")
    md.append("")
    (OUT / "summary.md").write_text("\n".join(md), encoding="utf-8")
    print(f"T02 measures={s.measure.nunique()} values={len(s)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
