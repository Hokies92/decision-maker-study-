#!/usr/bin/env python3
"""p5_build_coded_instance.py — schema 1.2.0 example: the respondent-level text answers with the codes as a separate layer.

Inputs: 03_schema/examples/respondents_open_ended.xml (schema 1.1.0, generated by p3_build_instances.py; read, not changed),
        05_open_ended/codes.csv (P5.S05), the coding frame (p5_build_coding_frame.rows()).
Output: 03_schema/examples/respondents_coded.xml (schema 1.2.0):
    - every TextAnswer gains @id = the corpus answer_id (item + source row, as in p5_build_corpus.py);
    - a Coding section after Respondents: one CodeDef per frame code, one Applied per code applied to an answer;
        03_schema/schema_mapping_coding.csv — each P5 field → its XPath in the instance, with node counts checked there.
Verbatims are copied unchanged; the codes live only in Coding and reference answers by @id (keyref appliedAnswerRef).
The three 1.1.0 instances are left as they are — they must still validate against 1.2.0 (additive minor version).
Usage: python3 -I scripts/p5_build_coded_instance.py
"""
import re
import sys
from pathlib import Path

import pandas as pd
from lxml import etree

sys.dont_write_bytecode = True
sys.path.insert(0, str(Path(__file__).resolve().parent))
from p5_build_coding_frame import rows as frame_rows  # noqa: E402

SRC = Path("03_schema/examples/respondents_open_ended.xml")
OUT = Path("03_schema/examples/respondents_coded.xml")
CODES = Path("05_open_ended/codes.csv")
MAP = Path("03_schema/schema_mapping_coding.csv")
NS = "https://growthenablement.com/ns/dms/v1"
D = "{%s}" % NS
VERSION = "1.2.0"
FRAME_VERSION = "v1.1"


def main() -> int:
    parser = etree.XMLParser(remove_blank_text=True)
    doc = etree.parse(str(SRC), parser)
    root = doc.getroot()
    root.set("schemaVersion", VERSION)
    root.set("id", root.get("id") + "-CODED")
    ids = set()
    for a in root.iter(D + "TextAnswer"):
        m = re.search(r"!([A-Z]+)(\d+)$", a.get("cite"))
        aid = f"{a.get('item')}-R{int(m.group(2)):03d}"
        if aid in ids:
            print(f"ERROR: duplicate answer id {aid}", file=sys.stderr)
            return 2
        ids.add(aid)
        a.set("id", aid)
    codes = pd.read_csv(CODES, dtype=str, keep_default_na=False)
    missing = sorted(set(codes.answer_id) - ids)
    if missing:
        print("ERROR: coded answers not in the instance:", missing[:10], file=sys.stderr)
        return 2
    frame = frame_rows()
    known = {r["code"] for r in frame}
    unknown = sorted(set(codes.code) - known)
    if unknown:
        print("ERROR: codes not in the frame:", unknown, file=sys.stderr)
        return 2
    cod = etree.SubElement(root, D + "Coding", frameVersion=FRAME_VERSION)
    for r in frame:
        cd = etree.SubElement(cod, D + "CodeDef", id=r["code"], layer=r["layer"], label=r["label"],
                              origin=r["origin"] or "deductive", provenance="INFERRED")
        etree.SubElement(cd, D + "Definition").text = r["definition"]
        for tag, key in (("Include", "include"), ("Exclude", "exclude"), ("Example", "example")):
            if r.get(key):
                etree.SubElement(cd, D + tag).text = r[key]
    for x in codes.itertuples(index=False):
        attrs = {"answer": x.answer_id, "code": x.code}
        if x.polarity:
            attrs["polarity"] = x.polarity
        attrs.update(primary="true" if x.primary == "True" else "false", coder=x.coder, provenance=x.provenance)
        etree.SubElement(cod, D + "Applied", **attrs)
    OUT.write_bytes(etree.tostring(doc, pretty_print=True, xml_declaration=True, encoding="UTF-8"))
    nsm = {"d": NS}
    chk = etree.parse(str(OUT))
    cnt = lambda xp: int(chk.xpath(f"count({xp})", namespaces=nsm))
    mp = [("05_open_ended/corpus.csv", "answer_id", "/d:Study/d:Respondents/d:Respondent/d:TextAnswer/@id", len(ids)),
          ("05_open_ended/coding_frame.csv", "code", "/d:Study/d:Coding/d:CodeDef/@id", len(frame))]
    for layer in sorted(codes.layer.unique()):
        n = int((codes.layer == layer).sum())
        mp.append(("05_open_ended/codes.csv", f"layer={layer}",
                   f"/d:Study/d:Coding/d:Applied[@code = /d:Study/d:Coding/d:CodeDef[@layer='{layer}']/@id]", n))
    rows = []
    for src, field, xp, expected in mp:
        found = cnt(xp)
        if found != expected:
            print(f"ERROR: {xp}: {found} nodes, expected {expected}", file=sys.stderr)
            return 2
        rows.append({"source": src, "field": field, "xpath": xp, "nodes": found, "checked_in": OUT.name})
    pd.DataFrame(rows).to_csv(MAP, index=False, lineterminator="\n")
    print(f"answers={len(ids)} with id; codedefs={len(frame)}; applied={len(codes)} -> {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
