#!/usr/bin/env python3
"""T04 — value vs experience: what decision-makers say they value against what they report receiving.

Pairs are authored in 04_analytics_library/pairs.csv (INFERRED until Scott reviews them). For each pair
and each cohort where every measure is usable (n ≥ 25, base ≥ 25): a = value side (or 'self' side),
b = experience side (or 'customer' side), gap = b − a. Writes 04_analytics_library/outputs/T04/.
Usage: python3 -I scripts/p4_t04_value_vs_experience.py
"""
import csv
import sys
from pathlib import Path

sys.dont_write_bytecode = True
sys.path.insert(0, str(Path(__file__).resolve().parent))
import p4_lib as L  # noqa: E402

OUT = L.OUT / "T04"
PAIRS = Path("04_analytics_library/pairs.csv")
ALL = "C-L-ALL-RESPONDENTS"


def save_svg(fig, path):
    import matplotlib
    matplotlib.rcParams["svg.hashsalt"] = "dms-p4"
    fig.savefig(path, format="svg", metadata={"Date": None}, bbox_inches="tight")


def main() -> int:
    import matplotlib
    matplotlib.use("Agg")
    matplotlib.rcParams["svg.fonttype"] = "none"
    matplotlib.rcParams["font.family"] = ["DejaVu Sans"]   # bundled with matplotlib: same metrics on any machine
    import matplotlib.pyplot as plt
    import pandas as pd
    m = L.measures()
    idx = m.set_index(["measure", "cohort"])
    known = set(m.measure)
    pairs = list(csv.DictReader(PAIRS.open(encoding="utf-8")))
    rows, errors = [], []
    for p in pairs:
        a_ms, b_ms = p["a_measures"].split(";"), p["b_measures"].split(";")
        for x in a_ms + b_ms:
            if x not in known:
                errors.append(f"{p['pair_id']}: measure {x} not found")
        if errors:
            continue
        for c in sorted(set(m.cohort)):
            try:
                a = idx.loc[[(x, c) for x in a_ms]]
                b = idx.loc[[(x, c) for x in b_ms]]
            except KeyError:
                continue
            usable = bool(a.usable.all() and b.usable.all())
            rows.append({"pair_id": p["pair_id"], "pair_type": p["pair_type"], "gate": p["gate"], "concept": p["concept"],
                         "cohort": c, "dimension": a.dimension.iloc[0], "a_value": round(a.value.sum(), 4),
                         "b_value": round(b.value.sum(), 4), "gap": round(b.value.sum() - a.value.sum(), 4),
                         "a_base": int(a.base.min()), "b_base": int(b.base.min()), "usable": usable,
                         "provenance": p["provenance"]})
    if errors:
        for e in errors:
            print("ERROR:", e, file=sys.stderr)
        return 2
    df = pd.DataFrame(rows)
    L.write_csv(df, OUT / "value_vs_experience.csv")
    u = df[df.usable]
    spread = u.groupby("pair_id").gap.agg(cohorts="size", gap_min="min", gap_median="median", gap_max="max").round(4)
    spread["same_sign_everywhere"] = u.groupby("pair_id").gap.apply(lambda g: bool((g < 0).all() or (g > 0).all()))
    L.write_csv(spread.reset_index(), OUT / "gap_spread.csv")
    a = df[df.cohort == ALL].set_index("pair_id")
    fig, ax = plt.subplots(figsize=(8, 4.8))
    order = [p["pair_id"] for p in pairs]
    for k, pid in enumerate(reversed(order)):
        r = a.loc[pid]
        ax.plot([r.a_value, r.b_value], [k, k], color="0.6", lw=2, zorder=1)
        ax.scatter([r.a_value], [k], color="0.85", edgecolor="black", s=60, zorder=2, label="value / self" if k == 0 else None)
        ax.scatter([r.b_value], [k], color="black", s=60, zorder=2, label="received / customer" if k == 0 else None)
    ax.set_yticks(range(len(order)), [f"{pid} {a.loc[pid].concept}" for pid in reversed(order)], fontsize=8)
    ax.set_xlim(0, 1)
    ax.set_xlabel("share of decision-makers (All respondents, n = 319)")
    ax.legend(loc="lower right", fontsize=8, frameon=False)
    ax.set_title("What decision-makers value vs what they report receiving", fontsize=9)
    save_svg(fig, OUT / "value_vs_experience.svg")
    md = ["# T04 results — value vs experience", "", "Generated by `scripts/p4_t04_value_vs_experience.py` from `pairs.csv` "
          "(pairs INFERRED — for Scott's review). gap = received − valued (or customer − self); negative = less received "
          "than valued.", "", "| Pair | Concept | Valued / self | Received / customer | Gap (All) | Usable cohorts | "
          "Gap range | Same direction in every cohort |", "|---|---|---|---|---|---|---|---|"]
    for pid in order:
        r, s = a.loc[pid], spread.loc[pid]
        md.append(f"| {pid} | {r.concept} | {r.a_value:.2f} | {r.b_value:.2f} | {r.gap:+.2f} | {int(s.cohorts)} | "
                  f"{s.gap_min:+.2f} to {s.gap_max:+.2f} | {'yes' if s.same_sign_everywhere else 'no'} |")
    md += ["", "Chart: `value_vs_experience.svg`. All cohorts: `value_vs_experience.csv`.", ""]
    (OUT / "summary.md").write_text("\n".join(md), encoding="utf-8")
    print("T04", a.gap.to_dict())
    return 0


if __name__ == "__main__":
    sys.exit(main())
