#!/usr/bin/env python3
"""p5_summarize_codes.py — counts of each code in a long code table, by frame (best / worst / other).

Usage: python3 -I scripts/p5_summarize_codes.py <codes.csv> <summary.md> "<title>"
Behaviour codes are counted by polarity (+ / −). Every code in the frame is listed, used or not.
"""
import sys
from pathlib import Path

import pandas as pd

sys.dont_write_bytecode = True
sys.path.insert(0, str(Path(__file__).resolve().parent))
from p5_build_coding_frame import LAYERS, rows as frame_rows  # noqa: E402


def main() -> int:
    src, out, title = Path(sys.argv[1]), Path(sys.argv[2]), sys.argv[3]
    c = pd.read_csv(src, dtype=str, keep_default_na=False)
    fr = frame_rows()
    n_ans = c.answer_id.nunique()
    nc = c[c.layer == "notcodable"].answer_id.nunique()
    L = [f"# {title}", "", f"Generated by `scripts/p5_summarize_codes.py` from `{src.name}`. {n_ans} answers; {nc} not codable; "
         f"{n_ans - nc} coded on every layer that applies. Counts are answers carrying the code (any position); "
         "'primary' = answers where it is the first code in its layer.", ""]
    for layer, name in LAYERS.items():
        codes = [r for r in fr if r["layer"] == layer]
        sub = c[c.layer == layer]
        L += [f"## {name}", ""]
        if layer == "behaviour":
            L += ["| Code | Label | + best | + other | − worst | − other | Primary |", "|---|---|---|---|---|---|---|"]
            for r in codes:
                s = sub[sub.code == r["code"]]
                pb = int(((s.polarity == "+") & (s.frame == "best")).sum()); po = int(((s.polarity == "+") & (s.frame != "best")).sum())
                nw = int(((s.polarity == "-") & (s.frame == "worst")).sum()); no = int(((s.polarity == "-") & (s.frame != "worst")).sum())
                L.append(f"| {r['code']} | {r['label']} | {pb} | {po} | {nw} | {no} | {int((s.primary == 'True').sum())} |")
        else:
            L += ["| Code | Label | Answers | Best | Worst | Other | Primary |", "|---|---|---|---|---|---|---|"]
            for r in codes:
                s = sub[sub.code == r["code"]]
                L.append(f"| {r['code']} | {r['label']} | {s.answer_id.nunique()} | {int((s.frame == 'best').sum())} | "
                         f"{int((s.frame == 'worst').sum())} | {int((~s.frame.isin(['best', 'worst'])).sum())} | {int((s.primary == 'True').sum())} |")
        L.append("")
    out.write_text("\n".join(L), encoding="utf-8")
    print(f"answers={n_ans}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
