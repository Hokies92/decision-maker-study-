#!/usr/bin/env python3
"""T08 — cohort similarity and clusters: which cohorts have the most similar experience across all questions.

Usable cohorts × headline measures (p4_lib.cohort_matrix, complete), each measure standardised across
cohorts (z-score); Euclidean distance between cohorts; hierarchical clustering (average linkage); clusters
at k = 4; each cohort's nearest neighbour. ECOLOGICAL: cohorts overlap. Writes outputs/T08/.
Usage: python3 -I scripts/p4_t08_cohort_similarity.py
"""
import sys
from pathlib import Path

sys.dont_write_bytecode = True
sys.path.insert(0, str(Path(__file__).resolve().parent))
import p4_lib as L  # noqa: E402

OUT = L.OUT / "T08"
K = 4


def save_svg(fig, path):
    import matplotlib
    matplotlib.rcParams["svg.hashsalt"] = "dms-p4"
    fig.savefig(path, format="svg", metadata={"Date": None}, bbox_inches="tight")


def main() -> int:
    import matplotlib
    matplotlib.use("Agg")
    matplotlib.rcParams["svg.fonttype"] = "none"
    import matplotlib.pyplot as plt
    import numpy as np
    import pandas as pd
    from scipy.cluster.hierarchy import dendrogram, fcluster, linkage
    from scipy.spatial.distance import pdist, squareform
    wide, _ = L.cohort_matrix()
    wide = wide.dropna(axis=1)
    z = (wide - wide.mean()) / wide.std(ddof=0)
    z = z.loc[:, wide.std(ddof=0) > 0]
    co = L.cohorts(L.load()).set_index("cohort")
    names = [f"{co.loc[c, 'label']} ({co.loc[c, 'dimension'].replace('D-', '')})" for c in z.index]
    D = pdist(z.values, metric="euclidean")
    Z = linkage(D, method="average")
    cl = fcluster(Z, t=K, criterion="maxclust")
    sq = squareform(D)
    np.fill_diagonal(sq, np.inf)
    nn = sq.argmin(axis=1)
    out = pd.DataFrame({"cohort": z.index, "label": names, "dimension": [co.loc[c, "dimension"] for c in z.index],
                        "n": [int(co.loc[c, "n"]) for c in z.index], "cluster": cl,
                        "nearest": [z.index[j] for j in nn], "nearest_distance": np.round(sq[np.arange(len(nn)), nn], 4),
                        "distance_to_centre": np.round(np.sqrt((z.values ** 2).sum(axis=1)), 4)})
    L.write_csv(out, OUT / "cohort_clusters.csv")
    dist = pd.DataFrame(np.round(squareform(D), 4), index=z.index, columns=z.index)
    dist.index.name = "cohort"
    L.write_csv(dist.reset_index(), OUT / "cohort_distances.csv")
    prof = pd.DataFrame(z.values, index=cl, columns=z.columns).groupby(level=0).mean().round(3)
    prof.index.name = "cluster"
    L.write_csv(prof.reset_index(), OUT / "cluster_profiles_z.csv")
    fig, ax = plt.subplots(figsize=(8, 9))
    dendrogram(Z, labels=names, orientation="right", ax=ax, color_threshold=0, above_threshold_color="black",
               leaf_font_size=6)
    ax.set_title(f"Cohorts by similarity of experience across {z.shape[1]} questions (average linkage; ecological)", fontsize=8)
    save_svg(fig, OUT / "cohort_dendrogram.svg")
    md = ["# T08 results — cohort similarity and clusters", "", "Generated by `scripts/p4_t08_cohort_similarity.py`. "
          f"{z.shape[0]} usable cohorts × {z.shape[1]} headline measures (z-scores), Euclidean distance, average linkage, "
          f"{K} clusters. Ecological: cohorts overlap (e.g. a country and its region), so similar pairs are partly the same people.", ""]
    for k in sorted(set(cl)):
        mem = out[out.cluster == k]
        hi = prof.loc[k].sort_values(ascending=False)
        md += [f"## Cluster {k} — {len(mem)} cohorts", "", ", ".join(mem.label), "",
               "Highest relative to other cohorts: " + "; ".join(f"{m} ({v:+.1f} sd)" for m, v in hi.head(3).items()) + ".",
               "Lowest: " + "; ".join(f"{m} ({v:+.1f} sd)" for m, v in hi.tail(3).iloc[::-1].items()) + ".", ""]
    far = out.sort_values("distance_to_centre", ascending=False).head(5)
    md += ["## Most distinctive cohorts (farthest from the average profile)", "", "| Cohort | n | Distance |", "|---|---|---|"]
    for x in far.itertuples():
        md.append(f"| {x.label} | {x.n} | {x.distance_to_centre:.1f} |")
    md += ["", "Files: `cohort_clusters.csv`, `cohort_distances.csv`, `cluster_profiles_z.csv`, `cohort_dendrogram.svg`.", ""]
    (OUT / "summary.md").write_text("\n".join(md), encoding="utf-8")
    print("T08 clusters", out.cluster.value_counts().sort_index().to_dict())
    return 0


if __name__ == "__main__":
    sys.exit(main())
