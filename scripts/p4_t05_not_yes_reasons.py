#!/usr/bin/env python3
"""T05 — not-yes reasons: why decision-makers pulled back after initial interest (Q15), by cohort.

Each reason's share per cohort; whether the vendor can see the reason (Q15_1: went with another vendor)
or it happens inside the customer's company (Q15_2–Q15_6) — classification INFERRED (Claude).
Q15 is multi-select: shares do not add across reasons. Writes 04_analytics_library/outputs/T05/.
Usage: python3 -I scripts/p4_t05_not_yes_reasons.py
"""
import sys
from pathlib import Path

sys.dont_write_bytecode = True
sys.path.insert(0, str(Path(__file__).resolve().parent))
import p4_lib as L  # noqa: E402

OUT = L.OUT / "T05"
ALL = "C-L-ALL-RESPONDENTS"
WHERE = {"Q15_1": "visible to the vendor", "Q15_2": "inside the customer's company", "Q15_3": "inside the customer's company",
         "Q15_4": "inside the customer's company", "Q15_5": "inside the customer's company",
         "Q15_6": "inside the customer's company", "Q15_7": "other", "Q15_8": "don't know"}


def save_svg(fig, path):
    import matplotlib
    matplotlib.rcParams["svg.hashsalt"] = "dms-p4"
    fig.savefig(path, format="svg", metadata={"Date": None}, bbox_inches="tight")


def main() -> int:
    import matplotlib
    matplotlib.use("Agg")
    matplotlib.rcParams["svg.fonttype"] = "none"
    import matplotlib.pyplot as plt
    m = L.measures()
    q = m[m.item.isin(WHERE) & (m.kind == "selection")].copy()
    q["where"] = q.item.map(WHERE)
    q["where_provenance"] = "INFERRED"
    q["rank_in_cohort"] = q.groupby("cohort").value.rank(ascending=False, method="min").astype(int)
    q = q.sort_values(["cohort", "item"], kind="stable")[["item", "label", "where", "where_provenance", "cohort",
                                                           "dimension", "value", "base", "n", "usable", "rank_in_cohort"]]
    L.write_csv(q, OUT / "reasons_by_cohort.csv")
    u = q[q.usable & q.item.isin([k for k, v in WHERE.items() if v in ("visible to the vendor", "inside the customer's company")])]
    top = u[u.rank_in_cohort == 1].groupby("item").cohort.size()
    f = L.flags(L.load())
    fq = f[f.thread == "T-Q15"]
    fq = fq[(fq.state != "notTested") & (fq.dimension != "ALL")]
    sig = fq.groupby("dimension").state.apply(lambda s: f"{int((s == 'significant').sum())} of {len(s)}")
    a = q[q.cohort == ALL].sort_values("value", ascending=True, kind="stable")
    fig, ax = plt.subplots(figsize=(8, 4))
    colors = ["black" if w == "visible to the vendor" else "0.6" if w.startswith("inside") else "0.9" for w in a["where"]]
    ax.barh(range(len(a)), a.value, color=colors, edgecolor="black")
    ax.set_yticks(range(len(a)), [l[:70] for l in a.label], fontsize=7)
    ax.set_xlim(0, 0.6)
    ax.set_xlabel("share who pulled back for this reason (All respondents; more than one allowed)")
    ax.set_title("Why decision-makers pulled back — black: the vendor sees it; grey: it happens inside the customer's company",
                 fontsize=8)
    save_svg(fig, OUT / "not_yes_reasons.svg")
    md = ["# T05 results — not-yes reasons", "", "Generated by `scripts/p4_t05_not_yes_reasons.py`. Q15: \"Think of a situation "
          "where you were initially interested … but you chose to pull back.\" More than one reason allowed.", "",
          "| Reason | Where it happens (INFERRED) | All respondents |", "|---|---|---|"]
    for x in a.sort_values("value", ascending=False).itertuples():
        md.append(f"| {x.label} | {x.where} | {x.value:.2f} |")
    md += ["", f"Top reason across the {u.cohort.nunique()} usable cohorts: " +
           "; ".join(f"{k} in {v}" for k, v in top.sort_values(ascending=False).items()) + " (a tie counts for each reason).", "",
           "Where groups differ on Q15 (source significance flags): " + "; ".join(f"{k} {v}" for k, v in sig.items()) + ".",
           "", "Chart: `not_yes_reasons.svg`. All cohorts: `reasons_by_cohort.csv`.", ""]
    (OUT / "summary.md").write_text("\n".join(md), encoding="utf-8")
    print("T05 top reasons", top.to_dict())
    return 0


if __name__ == "__main__":
    sys.exit(main())
