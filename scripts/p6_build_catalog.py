#!/usr/bin/env python3
"""p6_build_catalog.py — 06_visualization/catalog.md: every view, its question, unit, sources, and where it is built and published.

Inputs: 06_visualization/data/*.json (meta, P6.S03); 06_visualization/published.csv (authored: page, views, file, URL).
Usage: python3 -I scripts/p6_build_catalog.py
"""
import csv
import json
import sys
from pathlib import Path

V = Path("06_visualization")


def main() -> int:
    metas = [json.loads(p.read_text(encoding="utf-8"))["meta"] for p in sorted((V / "data").glob("v*.json")) + [V / "data/findings.json"]]
    pages = list(csv.DictReader((V / "published.csv").open(encoding="utf-8")))
    where = {v: p for p in pages for v in p["views"].split(";")}
    L = ["# Phase 6 catalog", "", "Generated by `scripts/p6_build_catalog.py` from the view data (`data/`) and `published.csv`. Do not edit by hand.", "",
         "| View | Name | Question | Unit | Built in | Published |", "|---|---|---|---|---|---|"]
    for m in metas:
        p = where.get(m["view"])
        built = f"`{p['file']}` ({p['page']})" if p else "not built yet"
        pub = f"[{p['page']}]({p['published_url']}) — {p['shared']}" if p and p["published_url"] else "—"
        L.append(f"| {m['view']} | {m['title']} | {m['question']} | {m['unit']} | {built} | {pub} |")
    L += ["", "## Sources and caveats per view", ""]
    for m in metas:
        L += [f"### {m['view']} — {m['title']}", "", "Sources: " + ", ".join(f"`{s}`" for s in m["sources"]), "",
              *[f"- {c}" for c in m["caveats"]], "", f"Provenance: {m['provenance']}", ""]
    (V / "catalog.md").write_text("\n".join(L), encoding="utf-8")
    print(f"views={len(metas)} pages={len(pages)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
