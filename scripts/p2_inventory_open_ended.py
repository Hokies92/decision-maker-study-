#!/usr/bin/env python3
"""p2_inventory_open_ended.py — inventory of the respondent-level text (no coding).

Inputs (read-only): 00_source/data/open_ended.xlsx (SRC-003); 00_source/data/survey.xlsx "Other" sheet
Outputs: 02_data_inventory/open_ended_inventory.csv (per question) and open_ended_inventory.md

Per question Q21–Q25: respondents, answers, blanks, length in characters and words,
non-answers ("none", "n/a", "don't know", …), repeated identical answers. Across questions:
respondents answering all five, and overlap with the "please specify" answers.
Answer text is read, never changed or reproduced here (Phase 5 codes it).

Usage: python3 -I scripts/p2_inventory_open_ended.py
"""

from __future__ import annotations

import csv
import re
import statistics
import sys
from collections import Counter
from pathlib import Path

import pandas as pd

SRC2, SRC3 = Path("00_source/data/survey.xlsx"), Path("00_source/data/open_ended.xlsx")
OD = Path("02_data_inventory")
OUT_CSV, OUT_MD = OD / "open_ended_inventory.csv", OD / "open_ended_inventory.md"
NON_ANSWER = re.compile(r"^\s*(none|n/?a|na|no|nothing|nobody|no one|don'?t know|dont know|dk|not sure|unsure|"
                        r"no comment|-+|\.+|\?+|x+)\s*\.?\s*$", re.I)
FIELDS = ["question", "respondents", "answers", "blank", "non_answers", "chars_min", "chars_median", "chars_p90",
          "chars_max", "words_median", "repeated_answers", "most_repeated_count"]


def main() -> int:
    oe = pd.read_excel(SRC3, sheet_name=None, dtype=str)
    rows, answered, errors = [], {}, []
    for q, d in oe.items():
        d = d[d["respid"].notna()]
        text = d.iloc[:, 2].fillna("").astype(str).str.strip()
        ans = text[text != ""]
        if len(d) != 319:
            errors.append(f"{q}: {len(d)} respondents, expected 319")
        lens = sorted(ans.str.len())
        words = ans.str.split().str.len()
        counts = Counter(ans.str.lower())
        rep = {k: v for k, v in counts.items() if v > 1}
        answered[q] = set(d.loc[text != "", "respid"])
        rows.append({"question": q, "respondents": len(d), "answers": len(ans), "blank": len(d) - len(ans),
                     "non_answers": int(ans.map(lambda s: bool(NON_ANSWER.match(s))).sum()),
                     "chars_min": lens[0], "chars_median": int(statistics.median(lens)),
                     "chars_p90": lens[int(0.9 * (len(lens) - 1))], "chars_max": lens[-1],
                     "words_median": int(statistics.median(words)), "repeated_answers": len(rep),
                     "most_repeated_count": max(rep.values()) if rep else 0})
    if errors:
        for e in errors:
            print("ERROR:", e, file=sys.stderr)
        return 2
    all5 = set.intersection(*answered.values())
    other = pd.read_excel(SRC2, sheet_name='"Other" Text Answers', dtype=str)
    other = other[other["respid"].notna()]
    spec = []
    for c in other.columns[1:]:
        v = other[c].fillna("").astype(str).str.strip()
        ids = set(other.loc[v != "", "respid"])
        if ids:
            spec.append((str(c).split(":")[0].split(" ")[0], len(ids), len(ids & all5)))
    with OUT_CSV.open("w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=FIELDS, lineterminator="\n")
        w.writeheader(); w.writerows(rows)
    L = ["# Open-Ended Inventory", "", "Generated by `scripts/p2_inventory_open_ended.py`. Counts only — answer text is "
         "unchanged and not reproduced here; coding is Phase 5.", "",
         "| Question | Respondents | Answers | Blank | Non-answers | Median chars | 90th pct chars | Max chars | Median words | Repeated answers |",
         "|---|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        L.append(f"| {r['question']} | {r['respondents']} | {r['answers']} | {r['blank']} | {r['non_answers']} | "
                 f"{r['chars_median']} | {r['chars_p90']} | {r['chars_max']} | {r['words_median']} | "
                 f"{r['repeated_answers']} (most: {r['most_repeated_count']}×) |")
    L += ["", f"**Respondents who answered all five:** {len(all5)} of 319.", "",
          "## Overlap with 'please specify' answers (respondent-level links)", "",
          "| Column | Respondents with text | Of whom answered all five open-ended |", "|---|---|---|"]
    for c, n, k in spec:
        L.append(f"| {c} | {n} | {k} |")
    L += ["", "Non-answers are matched by pattern (e.g. 'none', 'n/a', 'don't know'); they are counted, not removed.", ""]
    OUT_MD.write_text("\n".join(L), encoding="utf-8")
    print(f"questions={len(rows)} all_five={len(all5)} specify_columns={len(spec)}")
    for r in rows:
        print(" ", r["question"], r["answers"], "answers,", r["non_answers"], "non-answers, median", r["chars_median"], "chars")
    return 0


if __name__ == "__main__":
    sys.exit(main())
