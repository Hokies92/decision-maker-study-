#!/usr/bin/env python3
"""p1_build_question_list.py — the questions in survey order, for Scott to group.

Inputs (read-only):
    01_instrument_reconstruction/question_map.csv
    01_instrument_reconstruction/derived/table_blocks.csv
Outputs:
    01_instrument_reconstruction/question_list.md     readable list
    01_instrument_reconstruction/question_list.xlsx   worksheet with a blank "Scott's group" column

One entry per question (thread), in order S1–S12, Q1–Q25. Wording VERBATIM from the
source (via question_map.csv). Sub-items (for grids and multi-select lists) or answer
options (for single-choice questions) are listed so the question can be judged as a whole.
Derived items, the attention check, and "please specify" text columns are left out —
they are not questions a respondent was asked as such.

Usage: python3 -I scripts/p1_build_question_list.py
"""

from __future__ import annotations

import csv
import json
import sys
from collections import OrderedDict
from pathlib import Path

from openpyxl import Workbook
from openpyxl.styles import Alignment, Font, PatternFill

QMAP = Path("01_instrument_reconstruction/question_map.csv")
BLOCKS = Path("01_instrument_reconstruction/derived/table_blocks.csv")
OUT_MD = Path("01_instrument_reconstruction/question_list.md")
OUT_XLSX = Path("01_instrument_reconstruction/question_list.xlsx")
CANON = "Industry 7"

TYPE_WORDS = {
    "single_select": "Pick one",
    "grid_row": "Rate each",
    "multi_select_option": "Pick all that apply",
    "open_text": "Open answer",
}


def main() -> int:
    items = list(csv.DictReader(QMAP.open(encoding="utf-8")))
    blocks = {(b["sheet"], b["header_row"]): b for b in csv.DictReader(BLOCKS.open(encoding="utf-8"))}

    questions: "OrderedDict[str, dict]" = OrderedDict()
    for it in items:
        if it["item_role"] != "asked" or it["question_type"] == "open_text_specify":
            continue
        q = questions.setdefault(it["thread_id"], {"items": []})
        q["items"].append(it)
    # A question that survives only in derived (bucketed) form, e.g. S8, is still a question.
    for it in items:
        if it["thread_id"] not in questions and it["item_role"] == "derived":
            questions[it["thread_id"]] = {"items": [it]}
    order = sorted(questions, key=lambda t: (t[2] != "S", int(t[3:])))
    questions = OrderedDict((t, questions[t]) for t in order)

    rows = []
    for tid, q in questions.items():
        its = q["items"]
        first = its[0]
        qid = tid[2] + str(int(tid[3:]))
        qtype = TYPE_WORDS.get(first["question_type"], first["question_type"])
        stem = next((i["stem"] for i in its if i["stem_complete"] == "yes" and i["stem"]), first["stem"])
        def opts(it):
            b = blocks[(CANON, it["options_ref"].rsplit(" ", 1)[-1])]
            return json.loads(b["options_json"])

        qt = first["question_type"]
        if qt == "grid_row":
            detail_label, detail = "Statements rated", [i["item_label"] for i in its if i["item_label"]]
            extra = "Scale: " + " / ".join(opts(first))
        elif qt == "multi_select_option":
            detail_label, detail, extra = "Choices", [i["item_label"] for i in its if i["item_label"]], ""
        elif qt == "single_select":
            detail_label, extra = "Answer options", ""
            if len(its) == 1:
                detail = opts(first)
            else:  # several single-choice parts (e.g. Q20 limit, then amount)
                detail = []
                for k, i in enumerate(its, 1):
                    detail.append(f"Part {k} ({i['source_label_id']}): " + " / ".join(opts(i)))
        else:
            detail_label, detail, extra = "", [], ""
        base = first["base_all"]
        asked_of = "" if base in ("", "319") else f"Asked of {base} respondents (subset)"
        rows.append({"qid": qid, "stem": stem, "qtype": qtype, "detail_label": detail_label,
                     "detail": detail, "extra": extra, "asked_of": asked_of,
                     "cite": first["source_cite"]})

    # Markdown
    lines = [
        "# The Questions, In Order",
        "",
        "Generated by `scripts/p1_build_question_list.py`. Wording is exactly as in the source files.",
        "For Scott to group. Worksheet with a blank grouping column: `question_list.xlsx`.",
        "",
        f"{len(rows)} questions: S1–S12 (screener), Q1–Q20 (structured), Q21–Q25 (open-ended).",
        "",
    ]
    for r in rows:
        lines.append(f"**{r['qid']}.** {r['stem']}  ")
        meta = " · ".join(x for x in (r["qtype"], r["asked_of"]) if x)
        lines.append(f"*{meta}*")
        if r["detail"]:
            lines.append("")
            for d in r["detail"]:
                lines.append(f"- {d}")
        if r["extra"]:
            lines += ["", f"*{r['extra']}*"]
        lines.append("")
    OUT_MD.write_text("\n".join(lines), encoding="utf-8")

    # Worksheet
    wb = Workbook()
    ws = wb.active
    ws.title = "Questions"
    head = ["#", "Question", "Wording (as asked)", "Type", "Statements / choices / options", "Asked of", "Scott's group", "Notes"]
    ws.append(head)
    for c in ws[1]:
        c.font = Font(bold=True)
        c.fill = PatternFill("solid", fgColor="DDDDDD")
    for n, r in enumerate(rows, 1):
        detail = "\n".join(f"• {d}" for d in r["detail"])
        if r["extra"]:
            detail = f"{detail}\n{r['extra']}" if detail else r["extra"]
        ws.append([n, r["qid"], r["stem"], r["qtype"], detail, r["asked_of"] or "All 319", "", ""])
    widths = [5, 9, 60, 18, 60, 22, 18, 30]
    for i, w in enumerate(widths):
        ws.column_dimensions[chr(65 + i)].width = w
    for row in ws.iter_rows(min_row=2):
        for c in row:
            c.alignment = Alignment(wrap_text=True, vertical="top")
    for c in ws["G"][1:]:
        c.fill = PatternFill("solid", fgColor="FFF2CC")
    ws.freeze_panes = "C2"
    wb.properties.creator = ""
    wb.properties.lastModifiedBy = ""
    wb.save(OUT_XLSX)

    print(f"questions={len(rows)} → {OUT_MD}, {OUT_XLSX}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
