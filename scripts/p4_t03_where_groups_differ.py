#!/usr/bin/env python3
"""T03 — where groups differ: share of significance tests that are significant, by gate × dimension.

Reads the significance flags in full_study.xml through p4_lib. Writes 04_analytics_library/outputs/T03/.
At 95% confidence about 5% of tests are significant by chance alone.
Usage: python3 -I scripts/p4_t03_where_groups_differ.py
"""
import sys
from pathlib import Path

sys.dont_write_bytecode = True
sys.path.insert(0, str(Path(__file__).resolve().parent))
import p4_lib as L  # noqa: E402

OUT = L.OUT / "T03"
FEW = 10          # fewer tests than this in a cell: shown, marked 'few tests'
GATES = ["baseline", "ACCESS", "AGREE", "VISION", "CASE"]


def save_svg(fig, path):
    import matplotlib
    matplotlib.rcParams["svg.hashsalt"] = "dms-p4"
    fig.savefig(path, format="svg", metadata={"Date": None}, bbox_inches="tight")


def main() -> int:
    import matplotlib
    matplotlib.use("Agg")
    matplotlib.rcParams["svg.fonttype"] = "none"
    matplotlib.rcParams["font.family"] = ["DejaVu Sans"]   # bundled with matplotlib: same metrics on any machine
    import matplotlib.pyplot as plt
    import pandas as pd
    f = L.flags(L.load())
    f = f[(f.state != "notTested") & (f.dimension != "ALL") & f.gate.isin(GATES)]
    g = f.groupby(["gate", "dimension"]).state.agg(tested="size", significant=lambda s: int((s == "significant").sum()))
    g = g.reset_index()
    g["share_significant"] = (g.significant / g.tested).round(4)
    g["few_tests"] = g.tested < FEW
    g["gate_order"] = g.gate.map(GATES.index)
    g = g.sort_values(["gate_order", "dimension"], kind="stable").drop(columns="gate_order")
    tot = f.groupby("gate").state.agg(tested="size", significant=lambda s: int((s == "significant").sum())).reindex(GATES)
    tot["share_significant"] = (tot.significant / tot.tested).round(4)
    L.write_csv(g, OUT / "significance_by_gate.csv")
    L.write_csv(tot.reset_index(), OUT / "significance_by_gate_total.csv")
    piv = g.pivot(index="dimension", columns="gate", values="share_significant")[GATES]
    fig, ax = plt.subplots(figsize=(7, 5))
    im = ax.imshow(piv.values, cmap="Greys", vmin=0, vmax=0.7, aspect="auto")
    ax.set_xticks(range(len(GATES)), GATES)
    ax.set_yticks(range(len(piv.index)), piv.index)
    for i in range(piv.shape[0]):
        for j in range(piv.shape[1]):
            v = piv.values[i, j]
            ax.text(j, i, f"{v:.0%}", ha="center", va="center", color="white" if v > 0.35 else "black", fontsize=8)
    ax.set_title("Share of tests where groups differ significantly (95%); chance ≈ 5%", fontsize=9)
    fig.colorbar(im, ax=ax, shrink=0.7)
    save_svg(fig, OUT / "significance_by_gate.svg")
    md = ["# T03 results — where groups differ", "", "Generated by `scripts/p4_t03_where_groups_differ.py`. "
          "Share of significance tests (source comments, 95%) that are significant, by gate and breakout dimension. "
          f"About 5% would be significant by chance. Cells with fewer than {FEW} tests are marked.", "",
          "| Gate | Tests | Significant | Share |", "|---|---|---|---|"]
    for gate, x in tot.iterrows():
        md.append(f"| {gate} | {int(x.tested)} | {int(x.significant)} | {x.share_significant:.0%} |")
    md += ["", "By dimension: `significance_by_gate.csv`; chart: `significance_by_gate.svg`.", ""]
    (OUT / "summary.md").write_text("\n".join(md), encoding="utf-8")
    print("T03", tot.share_significant.to_dict())
    return 0


if __name__ == "__main__":
    sys.exit(main())
