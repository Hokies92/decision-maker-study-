#!/usr/bin/env python3
"""p4_build_catalog.py — 04_analytics_library/catalog.md, generated from the technique files' front matter.

Usage: python3 -I scripts/p4_build_catalog.py
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

LIB = Path("04_analytics_library")


def front_matter(text):
    m = re.match(r"^---\n(.*?)\n---\n", text, re.S)
    fm, key = {}, None
    for line in (m.group(1) if m else "").splitlines():
        line = re.sub(r"\s+#.*$", "", line)
        if not line.strip():
            continue
        if line.startswith("  - ") and key:
            fm[key].append(line[4:].strip())
        elif ":" in line and not line.startswith(" "):
            key, val = line.split(":", 1)
            fm[key.strip()] = [] if val.strip() == "" else val.strip()
    return fm


def main() -> int:
    files = sorted(LIB.glob("T[0-9][0-9]-*.md"))
    L = ["# Analytics Library — Catalog", "",
         "Generated by `scripts/p4_build_catalog.py` from each technique's front matter. Do not edit by hand.", "",
         "Every technique reads the schema (`03_schema/examples/full_study.xml`, schema dms 1.1.0), works on "
         "group-level percentages, and never uses a cohort or item base below n = 25 in a comparison. "
         "Template: `TEMPLATE.md`. Field check: `scripts/p4_check_xpaths.py`.", "",
         f"**{len(files)} techniques.**", "",
         "| ID | Technique | Gates | Question | Validity | Ecological caveat | Output | Script |",
         "|---|---|---|---|---|---|---|---|"]
    for f in files:
        fm = front_matter(f.read_text(encoding="utf-8"))
        cells = [f"[{fm.get('id')}]({f.name})", fm.get("title", ""), fm.get("gates", ""), fm.get("question", ""),
                 fm.get("validity", ""), fm.get("ecological_caveat", ""), fm.get("output_form", ""),
                 f"`{fm.get('script', '')}`"]
        L.append("| " + " | ".join(str(c).replace("|", "/") for c in cells) + " |")
    if not files:
        L.append("| — | No techniques yet (added in P4.S03–S06) | | | | | | |")
    L.append("")
    (LIB / "catalog.md").write_text("\n".join(L), encoding="utf-8")
    print(f"techniques={len(files)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
